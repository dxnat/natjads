// Builds CSS custom properties from tokens/figma-variables.json.
// Usage: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(readFileSync(join(root, "tokens/figma-variables.json"), "utf8"));
const outDir = join(root, "tokens/css");
mkdirSync(outDir, { recursive: true });

const FONT_FALLBACKS = {
  Inter: 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif',
  "Roboto Mono": 'ui-monospace, SFMono-Regular, Menlo, monospace',
};
const SHADOW_PARTS = ["x", "y", "blur", "spread", "colour"];
const TYPE_PARTS = ["family", "font-size", "line-height", "weight", "letter-spacing"];

// Figma path "colour/action/primary/default" -> "--color-action-primary-default"
const cssName = (path) =>
  "--" + path.split("/").map((s) => (s === "colour" ? "color" : s)).join("-");

const leaf = (path) => path.split("/").pop();

function literal(v, name) {
  if (typeof v === "string" && v.startsWith("#")) return v;
  if (typeof v === "string") return `"${v}", ${FONT_FALLBACKS[v] ?? "sans-serif"}`;
  if (leaf(name) === "weight" || name.includes("/weight/")) return String(v);
  return v === 0 ? "0" : `${v}px`;
}

const value = (v, name) => (v && v.alias ? `var(${cssName(v.alias)})` : literal(v, name));

// Groups like elevation/card/{x,y,blur,spread,colour} or type/body/md/{family,...}
function composites(vars) {
  const groups = new Map();
  for (const v of vars) {
    const parts = v.name.split("/");
    const key = parts.slice(0, -1).join("/");
    if (!groups.has(key)) groups.set(key, new Set());
    groups.get(key).add(parts.at(-1));
  }
  const lines = [];
  for (const [g, leaves] of groups) {
    const n = cssName(g);
    if (SHADOW_PARTS.every((p) => leaves.has(p))) {
      lines.push(`${n}: ${SHADOW_PARTS.map((p) => `var(${n}-${p === "colour" ? "color" : p})`).join(" ")};`);
    } else if (TYPE_PARTS.every((p) => leaves.has(p))) {
      lines.push(`${n}: var(${n}-weight) var(${n}-font-size) / var(${n}-line-height) var(${n}-family);`);
    }
  }
  return lines;
}

const block = (selector, lines, indent = "") =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}\n`;

const header = (title) =>
  `/* ${title}\n * Generated by scripts/build-tokens.mjs from tokens/figma-variables.json — do not edit by hand.\n * Source: ${src.source}\n */\n\n`;

const [primitives, semantic, component] = src.collections;
const primitiveNames = new Set(primitives.variables.map((v) => cssName(v.name)));

// --- Primitives ------------------------------------------------------------
{
  const lines = primitives.variables.map((v) => `${cssName(v.name)}: ${value(v.values.Base, v.name)};`);
  lines.push("", "/* Composite shadows */", ...composites(primitives.variables));
  writeFileSync(join(outDir, "primitives.css"), header("01 Primitives") + block(":root", lines));
}

// --- Semantic (Light / Dark) -------------------------------------------------
{
  const shared = [];
  const light = [];
  const dark = [];
  const skipped = [];
  for (const v of semantic.variables) {
    const name = cssName(v.name);
    const { Light: l, Dark: d } = v.values;
    // A semantic token that aliases a primitive of the same CSS name would be a
    // self-reference (invalid in CSS); the primitive already provides it.
    if (l?.alias && cssName(l.alias) === name && primitiveNames.has(name) && JSON.stringify(l) === JSON.stringify(d)) {
      skipped.push(name);
      continue;
    }
    if (JSON.stringify(l) === JSON.stringify(d)) shared.push(`${name}: ${value(l, v.name)};`);
    else {
      light.push(`${name}: ${value(l, v.name)};`);
      dark.push(`${name}: ${value(d, v.name)};`);
    }
  }
  shared.push("", "/* Composite shadows & type */", ...composites(semantic.variables));
  const note = skipped.length ? `/* Provided by primitives (same name): ${skipped.join(", ")} */\n\n` : "";
  const css =
    header("02 Semantic — modes: Light (default), Dark") +
    note +
    block(":root", shared) +
    "\n" +
    block(':root,\n[data-theme="light"]', ["color-scheme: light;", ...light]) +
    "\n" +
    block('[data-theme="dark"]', ["color-scheme: dark;", ...dark]) +
    "\n@media (prefers-color-scheme: dark) {\n" +
    block(':root:not([data-theme="light"])', ["color-scheme: dark;", ...dark], "  ") +
    "}\n";
  writeFileSync(join(outDir, "semantic.css"), css);
}

// --- Component -----------------------------------------------------------------
{
  const lines = component.variables.map((v) => `${cssName(v.name)}: ${value(v.values.Base, v.name)};`);
  lines.push("", "/* Composite shadows & type */", ...composites(component.variables));
  // Re-declared on [data-theme] so scoped theme switches re-resolve the semantic aliases.
  writeFileSync(join(outDir, "components.css"), header("03 Component") + block(":root,\n[data-theme]", lines));
}

// --- Typography utility classes -----------------------------------------------
{
  const styles = [...new Set(
    semantic.variables.filter((v) => v.name.startsWith("type/") && leaf(v.name) === "family")
      .map((v) => v.name.split("/").slice(0, -1).join("/")),
  )];
  const css = styles
    .map((s) => {
      const n = cssName(s);
      return block(`.${n.slice(2)}`, [`font: var(${n});`, `letter-spacing: var(${n}-letter-spacing);`]);
    })
    .join("\n");
  writeFileSync(join(outDir, "typography.css"), header("Typography utility classes") + css);
}

writeFileSync(
  join(outDir, "index.css"),
  header("Design tokens entry point") +
    ['primitives', 'semantic', 'components', 'typography'].map((f) => `@import "./${f}.css";`).join("\n") + "\n",
);

console.log(`Built tokens into ${outDir}`);
