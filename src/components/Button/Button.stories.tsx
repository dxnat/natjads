import type { Meta, StoryObj } from "@storybook/react-vite";
import { fn } from "storybook/test";
import { useState } from "react";
import { Button } from "./Button";
import contract from "./button.contract.json";
import tokenContract from "./button.tokens.contract.json";

const meta = {
  title: "Components/Button",
  component: Button,
  args: { children: "Save changes", onPress: fn() },
  argTypes: {
    variant: { control: "inline-radio", options: ["primary", "secondary", "danger"] },
    size: { control: "inline-radio", options: ["sm", "md", "lg"] },
    isDisabled: { control: "boolean" },
    isPending: { control: "boolean" },
    children: { control: "text" },
  },
} satisfies Meta<typeof Button>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Playground: Story = {};

export const Variants: Story = {
  render: (args) => (
    <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
      <Button {...args} variant="primary">Primary</Button>
      <Button {...args} variant="secondary">Secondary</Button>
      <Button {...args} variant="danger">Delete</Button>
    </div>
  ),
};

export const Sizes: Story = {
  render: (args) => (
    <div style={{ display: "flex", gap: 12, alignItems: "center", flexWrap: "wrap" }}>
      <Button {...args} size="sm">Small</Button>
      <Button {...args} size="md">Medium</Button>
      <Button {...args} size="lg">Large</Button>
    </div>
  ),
};

export const Disabled: Story = {
  render: (args) => (
    <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
      <Button {...args} variant="primary" isDisabled>Primary</Button>
      <Button {...args} variant="secondary" isDisabled>Secondary</Button>
      <Button {...args} variant="danger" isDisabled>Delete</Button>
    </div>
  ),
};

const PlusIcon = () => (
  <svg width="16" height="16" viewBox="0 0 16 16" fill="none" aria-hidden="true">
    <path d="M8 3v10M3 8h10" stroke="currentColor" strokeWidth="2" strokeLinecap="round" />
  </svg>
);

export const WithIcon: Story = {
  render: (args) => (
    <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
      <Button {...args}>
        <PlusIcon /> New project
      </Button>
      <Button {...args} variant="secondary" aria-label="Add item">
        <PlusIcon />
      </Button>
    </div>
  ),
};

export const Pending: Story = {
  render: function Render(args) {
    const [pending, setPending] = useState(false);
    return (
      <Button
        {...args}
        isPending={pending}
        onPress={() => {
          setPending(true);
          setTimeout(() => setPending(false), 2000);
        }}
      >
        {pending ? "Saving…" : "Save changes"}
      </Button>
    );
  },
};

const ContractView = ({ file, data }: { file: string; data: unknown }) => (
  <div style={{ display: "grid", gap: 8 }}>
    <code style={{ font: "var(--type-caption)", color: "var(--color-content-secondary)" }}>{file}</code>
    <pre
      style={{
        margin: 0,
        padding: 16,
        overflow: "auto",
        font: "var(--type-code)",
        color: "var(--color-content-primary)",
        background: "var(--color-surface-default)",
        border: "1px solid var(--color-border-subtle)",
        borderRadius: "var(--radius-container)",
      }}
    >
      {JSON.stringify(data, null, 2)}
    </pre>
  </div>
);

const contractParams = { controls: { disable: true }, actions: { disable: true }, a11y: { disable: true } };

/** Component-level contract: props, bindings, states, anatomy, a11y and anchors. */
export const Contract: Story = {
  name: "Contract",
  parameters: contractParams,
  render: () => <ContractView file="src/components/Button/button.contract.json" data={contract} />,
};

